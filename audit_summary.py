#!/usr/bin/env python3
"""Summarize the independent audit: regeneration verification, FP64-vs-double-double evaluator agreement, classification agreement, host cross-check."""
import json, math
from pathlib import Path
ROOT = Path('/home/worker/lab/campaign'); AUD = ROOT / 'audit'; OUT = ROOT / 'writeup_results'
U = {'fp32': 2.0 ** -24, 'fp64': 2.0 ** -53}
res = json.load(open(AUD / 'audit_results.json')); cross = json.load(open(AUD / 'host_crosscheck.json')) if (AUD / 'host_crosscheck.json').exists() else {}
cases = {json.loads(l)['case_id']: json.loads(l) for l in open(OUT / 'cases.jsonl')} if (OUT / 'cases.jsonl').exists() else {}
n_cases = len(res); regen_ok = sum(1 for r in res.values() if r.get('a_hash_match')); b_ok = sum(1 for r in res.values() if r.get('b_hash_match')); largest = max((r['n'] for r in res.values() if r.get('a_hash_match')), default=None)
nsol = 0; agree = 0; disagree = []; maxratio = 0; maxabs = 0
for cid, r in res.items():
    c = cases.get(cid); tau = 100 * U[r['dtype']]
    for sha, s in r.get('solutions', {}).items():
        if not s.get('finite'): continue
        e64 = s.get('eta_fp64') or []; edd = s.get('eta_dd') or []
        for a, b in zip(e64, edd):
            if a is None or b is None: continue
            nsol += 1; p64 = a <= tau; pdd = b <= tau; agree += (p64 == pdd)
            if p64 != pdd: disagree.append((cid, sha[:12], a, b, tau))
            if b > 0: maxratio = max(maxratio, a / b)
            maxabs = max(maxabs, abs(a - b) / tau)
# host cross-check: classification agreement numpy fp64 / long double vs gpu fp64 at primary tau
hn = 0; hagree = 0; hagree_ld = 0; hdis = []
for cid, sols in cross.items():
    tau = 100 * U[res[cid]['dtype']]
    for sha, s in sols.items():
        for g, e, l in zip(s['eta_gpu_fp64'] or [], s['eta_numpy_fp64'] or [], s['eta_numpy_longdouble'] or []):
            if g is None or e is None: continue
            hn += 1; hagree += ((g <= tau) == (e <= tau)); hagree_ld += ((g <= tau) == (l <= tau))
            if (g <= tau) != (l <= tau): hdis.append((cid, sha[:12], g, e, l, tau))
md = f"""# Independent audit summary (generated by audit_summary.py)

## Regeneration verification (fresh process `build/mpaudit`, recipe only)
- cases audited: {n_cases}; stored-A hash reproduced: {regen_ok}/{n_cases}; stored-B hash reproduced: {b_ok}/{n_cases}
- largest regenerated matrix with hash match: n = {largest}
- mismatches: {[cid for cid, r in res.items() if not r.get('a_hash_match')]}

## Original-system residual recomputation of every saved finite solution
- (solution, RHS) pairs evaluated with FP64 and with double-double (compensated) residuals: {nsol}
- primary-profile (100 u_target) normwise classification agreement FP64 vs double-double: {agree}/{nsol}
- max ratio eta_fp64/eta_dd over all pairs: {maxratio:.3f}; max |eta_fp64 - eta_dd| / tau: {maxabs:.3e}
- disagreements (case, solution, eta_fp64, eta_dd, tau): {disagree[:20]}

## Host cross-check (numpy float64 and x86 long double, embedded n<=512 cases)
- pairs: {hn}; classification agreement numpy-FP64 vs GPU-FP64: {hagree}/{hn}; long-double vs GPU-FP64: {hagree_ld}/{hn}
- disagreements vs long double (case, solution, eta_gpu, eta_numpy64, eta_longdouble, tau): {hdis[:20]}
- Note: element-level ratios between evaluators differ by small-integer factors when residual entries sit at the rounding floor (e.g. Grcar cases); the classification agreement at the acceptance threshold is the relevant statistic. Disputed classifications near the threshold can be re-derived from the stored numerators.
"""
(OUT / 'tests').mkdir(parents=True, exist_ok=True); (OUT / 'tests' / 'AUDIT_SUMMARY.md').write_text(md); (AUD / 'AUDIT_SUMMARY.md').write_text(md); print(md[:1500])
